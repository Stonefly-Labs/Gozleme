"""Generates src/Gozleme.Api/Manifests/Rules/ReservedClaimFolds.cs: look-alike characters folded to ASCII letters and
digits for reserved-name matching (GOZ-0006 maintainer decision 2026-11-17, "built-in fold table"). The API runs with
InvariantGlobalization, where .NET applies no NFKC, so the folds are precomputed here from Python's Unicode data:
each code point in RANGES whose NFKC form, with combining marks removed, is ASCII letters or digits."""
import sys
import unicodedata

RANGES = [
    (0x00C0, 0x024F, "Latin-1 Supplement, Latin Extended-A/B"),
    (0x02B0, 0x02FF, "spacing modifier letters"),
    (0x1D2C, 0x1DBF, "phonetic modifier letters"),
    (0x1E00, 0x1EFF, "Latin Extended Additional"),
    (0x2070, 0x209F, "superscripts and subscripts"),
    (0x2100, 0x214F, "letterlike symbols"),
    (0x2160, 0x2188, "number forms (roman numerals)"),
    (0x2460, 0x24FF, "enclosed alphanumerics"),
    (0xFB00, 0xFB06, "Latin ligatures"),
    (0xFF00, 0xFFEF, "halfwidth and fullwidth forms"),
    (0x1D400, 0x1D7FF, "mathematical alphanumeric symbols"),
    (0x1F130, 0x1F189, "enclosed alphanumeric supplement"),
]


def fold(cp):
    text = unicodedata.normalize("NFKC", chr(cp))
    text = "".join(c for c in unicodedata.normalize("NFD", text) if unicodedata.category(c) != "Mn")
    text = text.replace("ı", "i")
    return text if text and text.isascii() and text.isalnum() and text != chr(cp) else None


pairs = [(cp, f) for lo, hi, _ in RANGES for cp in range(lo, hi + 1) if (f := fold(cp))]
pairs.append((0x0131, "i"))
pairs = sorted(set(pairs))
lines = []
for i in range(0, len(pairs), 8):
    lines.append("        " + " ".join(f'[0x{cp:X}] = "{f}",' for cp, f in pairs[i:i + 8]))
ranges = "\n".join(f"/// <item>U+{lo:04X}–U+{hi:04X} {name}</item>" for lo, hi, name in RANGES)
out = f'''// <auto-generated> by scripts/reserved-folds/generate.py (Python {sys.version_info.major}.{sys.version_info.minor}, Unicode {unicodedata.unidata_version}); do not edit.
using System.Collections.Frozen;

namespace Gozleme.Api.Manifests.Rules;

/// <summary>
/// Look-alike characters folded to ASCII letters and digits for reserved-name matching (maintainer decision
/// 2026-11-17, "built-in fold table"): each code point below whose NFKC form, without combining marks, is ASCII
/// alphanumeric. Not full NFKC; Greek and Cyrillic homoglyphs are not folded (research R6).
/// <list type="bullet">
{ranges}
/// </list>
/// </summary>
internal static class ReservedClaimFolds
{{
    public static readonly FrozenDictionary<int, string> Map = new Dictionary<int, string>
    {{
{chr(10).join(lines)}
    }}.ToFrozenDictionary();
}}
'''
open("src/Gozleme.Api/Manifests/Rules/ReservedClaimFolds.cs", "w", encoding="utf-8").write(out)
print(len(pairs), "folds")
